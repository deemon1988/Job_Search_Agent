def load_profile_context(filepath: str) -> Dict[str, Any]:
    p = Path(filepath)
    if not p.exists():
        # Fallback to relative path
        alt_p = Path(__file__).resolve().parent.parent / "data" / "profile_context.json"
        if alt_p.exists():
            p = alt_p
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)

